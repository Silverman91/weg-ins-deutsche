    WebResourceResponse serve(String p) {
        if (p == null || p.isEmpty() || p.endsWith("/")) p = (p == null ? "/" : p) + "index.html";
        String name = p.substring(p.lastIndexOf('/') + 1), ext = name.contains(".") ? name.substring(name.lastIndexOf('.') + 1).toLowerCase() : "";
        String mime = MIME.containsKey(ext) ? MIME.get(ext) : "application/octet-stream";
        Map<String, String> h = new HashMap<>();
        h.put("Cache-Control", "no-cache");
        try {
            InputStream in = getAssets().open("www" + p);
            if (mime.equals("text/html")) {
                String html = new String(readAll(in), StandardCharsets.UTF_8);
                int at = html.toLowerCase().indexOf("<head>");
                html = at < 0 ? SHIM + html : html.substring(0, at + 6) + SHIM + html.substring(at + 6);
                in = new ByteArrayInputStream(html.getBytes(StandardCharsets.UTF_8));
            }
            boolean text = mime.startsWith("text/") || mime.contains("json") || mime.contains("javascript") || mime.contains("xml");
            return new WebResourceResponse(mime, text ? "utf-8" : null, 200, "OK", h, in);
        } catch (Exception e) {
            return new WebResourceResponse("text/plain", "utf-8", 404, "Not Found", h, new ByteArrayInputStream(new byte[0]));
        }
    }

    static byte[] readAll(InputStream in) throws java.io.IOException {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        byte[] buf = new byte[16384];
        for (int n; (n = in.read(buf)) > 0; ) out.write(buf, 0, n);
        in.close();
        return out.toByteArray();
    }

    class Bridge {
        @JavascriptInterface
        public void saveFile(String name, String mime, String base64) {
            byte[] data = Base64.decode(base64, Base64.DEFAULT);
            runOnUiThread(() -> save(name.replaceAll("[\\\\/:*?\"<>|]", "_"), mime, data));
        }

        @JavascriptInterface
        public void mediaPlaying(boolean playing) {
            main.post(() -> {
                main.removeCallbacks(stopService);
                if (!playing) { if (serviceOn) main.postDelayed(stopService, IDLE_STOP_MS); return; }
                if (serviceOn) return;
                try {
                    Intent i = new Intent(MainActivity.this, AudioService.class);
                    if (Build.VERSION.SDK_INT >= 26) startForegroundService(i); else startService(i);
                    serviceOn = true;
                } catch (Exception e) { /* not allowed right now (app in background): try again on the next play */ }
            });
        }
    }

    void save(String name, String mime, byte[] data) {
        if (Build.VERSION.SDK_INT >= 29) {
            try {
                ContentValues v = new ContentValues();
                v.put(MediaStore.Downloads.DISPLAY_NAME, name);
                v.put(MediaStore.Downloads.MIME_TYPE, mime);
                v.put(MediaStore.Downloads.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS);
                Uri u = getContentResolver().insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, v);
                try (OutputStream o = getContentResolver().openOutputStream(u)) { o.write(data); }
                Toast.makeText(this, "Saved to Downloads: " + name, Toast.LENGTH_LONG).show();
                return;
            } catch (Exception e) { /* fall back to asking where to save */ }
        }
        pendingName = name; pendingMime = mime; pendingData = data;
        Intent i = new Intent(Intent.ACTION_CREATE_DOCUMENT).addCategory(Intent.CATEGORY_OPENABLE).setType(mime).putExtra(Intent.EXTRA_TITLE, name);
        try { startActivityForResult(i, SAVE); } catch (Exception e) { Toast.makeText(this, "Could not save " + name, Toast.LENGTH_LONG).show(); }
    }

    @Override
    protected void onActivityResult(int request, int result, Intent data) {
        super.onActivityResult(request, result, data);
        if (request == PICK && fileCallback != null) {
            Uri u = result == RESULT_OK && data != null ? data.getData() : null;
            fileCallback.onReceiveValue(u == null ? null : new Uri[]{u});
            fileCallback = null;
        } else if (request == SAVE && pendingData != null) {
            if (result == RESULT_OK && data != null && data.getData() != null) {
                try (OutputStream o = getContentResolver().openOutputStream(data.getData())) {
                    o.write(pendingData);
                    Toast.makeText(this, "Saved " + pendingName, Toast.LENGTH_LONG).show();
                } catch (Exception e) { Toast.makeText(this, "Could not save " + pendingName, Toast.LENGTH_LONG).show(); }
            }
            pendingData = null;
        }
    }

